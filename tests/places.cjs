'use strict';
const assert=require('node:assert/strict'),Model=require('../model.js'),Backup=require('../backup.js'),vm=require('node:vm'),fs=require('node:fs'),path=require('node:path');
let n=0;const op=(author,kind,activity,data)=>({id:'p'+(++n),author,name:'Test',time:n,kind,activity,data});
const budget={expected:6550,travel:null,stay:null,extra:null},url='data:image/png;base64,aGVsbG8=';
const base=[op('one','place-folder','folder',{title:'Pranzo di domenica'}),op('one','place-post','post',{folder:'folder',title:'Ristorante',description:'Da provare',kind:'restaurant',budget}),op('one','place-photo','post',{url,name:'foto.png'})];
const left=[...base,op('one','place-like','post',{liked:true}),op('one','place-comment','comment1',{post:'post',body:'Andiamo?'})];
const right=[...base,op('two','place-like','post',{liked:true}),op('two','place-comment','comment2',{post:'post',body:'Sì!'})];
for(const item of [...left,...right])Model.validateOp(item);
const project=items=>Model.project(items).places;
const merged=project([...left,...right]),reverse=project([...right,...left]);
assert.deepEqual(merged,reverse);assert.equal(merged.posts[0].likes.length,2);assert.equal(merged.posts[0].comments.length,2);assert.equal(merged.posts[0].photos.length,1);
const ui={Intl,state:{places:merged}};
vm.createContext(ui);vm.runInContext(fs.readFileSync(path.join(__dirname,'../places.js'),'utf8'),ui);
assert.equal(ui.placeTotal(merged.posts[0]),6550);
assert.equal(ui.placeTotal({kind:'trip',budget:{travel:10000,stay:20000,extra:2500}}),32500);
assert.equal(ui.placeTotal({kind:'restaurant',budget:{expected:null}}),null);
const updated=[...left,...right,op('two','place-like','post',{liked:false}),op('one','place-comment','comment1',{post:'post',body:'Testo modificato'}),op('two','place-delete-comment','comment2',{})];
assert.deepEqual(project(updated).posts[0].likes,['one']);assert.equal(project(updated).posts[0].comments.length,1);assert.equal(project(updated).posts[0].comments[0].body,'Testo modificato');
const mediaDeleted=[...updated,op('one','place-delete-photo','post',{mediaId:base[2].id})];
assert.equal(project(mediaDeleted).posts[0].photos.length,0);assert(!Model.compactOps(mediaDeleted).some(o=>o.id===base[2].id));
const folderDeleted=[...updated,op('two','place-delete-folder','folder',{})];
assert.equal(project(folderDeleted).folders.length,0);assert.equal(project(folderDeleted).posts.length,0);
assert(!Model.compactOps(folderDeleted).some(o=>o.kind==='place-photo'));
const postDeleted=[...updated,op('one','place-delete-post','post',{})];assert.equal(project(postDeleted).posts.length,0);
const invalid=[op('one','place-post','bad',{folder:'folder',title:'Bad',description:'',kind:'restaurant',budget:{...budget,expected:-1}}),op('one','place-like','post',{liked:'yes'})];
for(const value of invalid)assert.throws(()=>Model.validateOp(value));
// Exclusive, author-specific choices survive older hearts, offline merges and removals.
const second=op('one','place-post','post2',{folder:'folder',title:'Seconda proposta',description:'',kind:'other',budget});
const folder2=op('two','place-folder','folder2',{title:'Altre idee'});
const third=op('two','place-post','post3',{folder:'folder2',title:'Terza proposta',description:'',kind:'other',budget});
const legacy=[...left,...right,second,folder2,third,op('one','place-like','post2',{liked:true})];
let exclusive=project(legacy);
assert.deepEqual(exclusive.posts.find(p=>p.id==='post').likes,['two']);
assert.deepEqual(exclusive.posts.find(p=>p.id==='post2').likes,['one']);
const oneMoves=op('one','place-choice','folder',{post:'post'});
const twoMoves=op('two','place-choice','folder',{post:'post2'});
const independent=op('one','place-choice','folder2',{post:'post3'});
const offline=[...legacy,oneMoves,twoMoves,independent];
for(const item of offline)Model.validateOp(item);
assert.deepEqual(project(offline),project([...offline].reverse()));
for(const person of ['one','two'])for(const folder of ['folder','folder2'])assert(project(offline).posts.filter(p=>p.folder===folder&&p.likes.includes(person)).length<=1);
assert.deepEqual(project(offline).posts.find(p=>p.id==='post3').likes,['one']);
const cleared=[...offline,op('one','place-choice','folder',{post:null})];
assert.equal(project(cleared).posts.filter(p=>p.folder==='folder'&&p.likes.includes('one')).length,0);
const matched=[...offline,op('one','place-choice','folder',{post:'post2'})];
assert.deepEqual(project(matched).posts.find(p=>p.id==='post2').likes,['one','two']);
const gone=[...matched,op('one','place-delete-post','post2',{})];
assert.equal(project(gone).posts.filter(p=>p.folder==='folder'&&p.likes.includes('one')).length,0);
assert.throws(()=>Model.validateOp(op('one','place-choice','folder',{post:3})));
console.log('PASS: una sola scelta per persona e cartella, spostamento atomico, rimozione senza ripristinare vecchi like e conflitti offline deterministici');
// A new shared choice produces one notice, including when it arrives in a sync.
const nodes=new Map(),saved=new Map();let notices=0,open=false;
ui.author='one';ui.view='posti';ui.displayName=id=>id==='one'?'Persona 1':'Persona 2';
ui.settingsStorage={getItem:k=>saved.get(k),setItem:(k,v)=>saved.set(k,v)};
ui.document={querySelector:()=>open?{}:null};
ui.$=id=>{if(!nodes.has(id))nodes.set(id,{textContent:'',showModal(){notices++;open=true;}});return nodes.get(id);};
ui.state={places:project(offline)};ui.observePlaceMatches();assert.equal(notices,0);
ui.state={places:project(matched)};ui.observePlaceMatches();assert.equal(notices,1);
open=false;ui.observePlaceMatches();assert.equal(notices,1);
assert.equal(nodes.get('placeMatchPost').textContent,'Seconda proposta');
vm.runInContext('placeMatchesReady=false',ui);ui.observePlaceMatches();assert.equal(notices,1);
ui.state={places:project([...matched,op('one','place-choice','folder',{post:null})])};ui.observePlaceMatches();
ui.state={places:project([...matched,op('one','place-choice','folder',{post:'post2'})])};ui.observePlaceMatches();assert.equal(notices,2);
console.log('PASS: avviso Piace a entrambi una sola volta, anche dopo scambio, nuova scelta e riapertura');
(async()=>{const data={format:'tra-noi-v4',exportedAt:new Date().toISOString(),identity:{person:'one'},ops:matched};
const file=await Backup.create(data,'test.json');const restored=await Backup.read(file);for(const value of restored.ops)Model.validateOp(value);
assert.deepEqual(project(restored.ops),project(matched));
console.log('PASS: cartelle, proposte, budget totale, foto, cuori indipendenti, commenti modificabili, confluenze offline, eliminazioni e recupero backup');
})().catch(e=>{console.error(e);process.exit(1)});
